const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setContent('<textarea id="markdown-editor"></textarea><article id="markdown-preview" class="post-body markdown-preview" style="width:700px"></article>');
    await page.addStyleTag({ path: path.resolve('styles.css') });
    await page.addStyleTag({ content: '#markdown-editor { min-height: 80px; height: 80px; }' });
    await page.addScriptTag({ url: 'https://cdn.jsdelivr.net/npm/marked/marked.min.js' });
    await page.addScriptTag({ url: 'https://cdn.jsdelivr.net/npm/dompurify/dist/purify.min.js' });
    await page.addScriptTag({ path: path.resolve('public/image-layout.js') });
    const app = fs.readFileSync('script.js', 'utf8');
    const rendering = app.slice(app.indexOf('let markdownExtensionsConfigured'), app.indexOf('function plainTextFromMarkdown'));
    const update = app.slice(app.indexOf('function updateMarkdownPreview'), app.indexOf('function renderManagePosts'));
    await page.addScriptTag({ content: `function resolveLocalImages(s) { return s; }\n${rendering}\n${update}\ndocument.querySelector('#markdown-editor').addEventListener('input', updateMarkdownPreview);` });
    const image = 'data:image/svg+xml;base64,' + Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="600" height="300"><rect width="600" height="300" fill="steelblue"/></svg>').toString('base64');
    const source = `# 标题\n\n第一段\n\n![图片](${image})\n\n第二段\n\n第三段`;
    await page.locator('#markdown-editor').fill(source);
    await page.waitForFunction(() => document.querySelector('#markdown-preview img')?.naturalWidth > 0);
    const img = page.locator('#markdown-preview img');
    const before = await img.boundingBox();
    const handle = await page.locator('.image-resize-handle').boundingBox();
    await page.mouse.move(handle.x + 9, handle.y + 9);
    await page.mouse.down();
    await page.mouse.move(handle.x - 160, handle.y - 70, { steps: 8 });
    await page.mouse.up();
    const after = await img.boundingBox();
    assert.ok(after.width < before.width - 100, 'Drag resizes the image');
    assert.ok(Math.abs(after.width / after.height - 2) < .05, 'Aspect ratio is preserved');
    assert.match(await page.locator('#markdown-editor').inputValue(), /<!--blog-image:/);
    await page.getByRole('button', { name: '居右', exact: true }).click();
    const aligned = await img.boundingBox();
    assert.ok(aligned.x > before.x + 100, 'Right alignment moves the image');
    await page.getByRole('button', { name: '居左', exact: true }).click();
    const drag = await img.boundingBox();
    await page.mouse.move(drag.x + 40, drag.y + 40);
    await page.mouse.down();
    await page.mouse.move(drag.x + 100, drag.y + 40, { steps: 6 });
    await page.mouse.up();
    assert.ok((await img.boundingBox()).x > drag.x + 40, 'Horizontal dragging persists');
    const frame = await page.locator('.editable-image').boundingBox();
    for (const alignment of [0.5, 1, 0]) {
      const box = await img.boundingBox();
      const expectedX = frame.x + (frame.width - box.width) * alignment;
      const nearX = expectedX + (alignment === 1 ? -7 : 7);
      await page.mouse.move(box.x + 30, box.y + 30);
      await page.mouse.down();
      await page.mouse.move(nearX + 30, box.y + 30, { steps: 8 });
      assert.equal(await page.locator('.image-alignment-guide:visible').count(), 1);
      const ghost = await page.locator('.image-drag-ghost').boundingBox();
      assert.ok(Math.abs(ghost.x - expectedX) < 1, 'Ghost snaps to the guide');
      await page.mouse.up();
      assert.ok(Math.abs((await img.boundingBox()).x - expectedX) < 1, 'Saved image retains snap alignment');
      assert.equal(await page.locator('.image-alignment-guide').count(), 0);
    }
    const saved = await page.locator('#markdown-editor').inputValue();
    await page.screenshot({ path: '.wrangler/image-layout-preview.png', fullPage: true });
    const published = await page.evaluate(s => {
      const div = document.createElement('div'); div.innerHTML = renderMarkdown(s);
      return { style: div.querySelector('img').getAttribute('style'), controls: div.querySelectorAll('button,.image-drop-anchor').length };
    }, saved);
    assert.match(published.style, /width:/);
    assert.equal(published.controls, 0);
    const anchors = page.locator('.image-drop-anchor');
    const last = await anchors.last().boundingBox();
    const moving = await img.boundingBox();
    await page.mouse.move(moving.x + 30, moving.y + 30);
    await page.mouse.down();
    await page.mouse.move(moving.x + 30, last.y + 8, { steps: 10 });
    await page.mouse.up();
    const reordered = await page.locator('#markdown-editor').inputValue();
    assert.ok(reordered.indexOf('![图片]') > reordered.indexOf('第三段'), 'Image moves after the final paragraph');
    assert.equal((reordered.match(/!\[图片\]/g) || []).length, 1);
    await page.locator('#markdown-editor').fill(reordered);
    assert.match(await img.getAttribute('style'), /width:/);
    const codeTest = await page.evaluate(src => {
      const sample = '```md\n' + src + '\n```\n\n' + src;
      return BlogImageLayout.inspect(sample).images.map(item => item.start);
    }, `![图片](${image})`);
    assert.equal(codeTest.length, 1, 'Code samples are not editable images');
    await page.locator('#markdown-editor').fill(`![参考](${image})<!--blog-image:40:18-->\n\n![移动](${image})<!--blog-image:30:0-->`);
    const reference = await page.locator('#markdown-preview img').first().boundingBox();
    const second = page.locator('#markdown-preview img').nth(1);
    const secondBox = await second.boundingBox();
    await page.mouse.move(secondBox.x + 25, secondBox.y + 25);
    await page.mouse.down();
    await page.mouse.move(reference.x + 25 + 6, secondBox.y + 25, { steps: 8 });
    await page.mouse.up();
    assert.ok(Math.abs((await second.boundingBox()).x - reference.x) < 1, 'Aligns with another image edge');
    // A nearby image used to keep the dragged image stuck short of the left edge.
    await page.locator('#markdown-editor').fill(`![参考](${image})<!--blog-image:40:2.5-->\n\n![移动](${image})<!--blog-image:30:20-->`);
    const edgeFrame = await page.locator('.editable-image').nth(1).boundingBox();
    const edgeImage = await second.boundingBox();
    await page.mouse.move(edgeImage.x + 20, edgeImage.y + 20);
    await page.mouse.down();
    await page.mouse.move(edgeFrame.x + edgeFrame.width * .025 + 20, edgeImage.y + 20);
    await page.mouse.move(edgeFrame.x + 20, edgeImage.y + 20);
    await page.mouse.up();
    assert.ok(Math.abs((await second.boundingBox()).x - edgeFrame.x) < 1, 'Nearby snap cannot block leftmost position');

    await page.locator('#markdown-editor').fill(`开头\n\n![A](${image})<!--blog-image:40:0-->\n\n中间文字\n\n![B](${image})<!--blog-image:40:0-->\n\n![C](${image})<!--blog-image:40:0-->\n\n结尾`);
    const a = await page.locator('img[alt="A"]').boundingBox();
    const b = await page.locator('img[alt="B"]').boundingBox();
    await page.mouse.move(b.x + 25, b.y + 25);
    await page.mouse.down();
    await page.mouse.move(a.x + a.width + 30, a.y + 30, { steps: 8 });
    assert.equal(await page.locator('.is-row-drop-right').count(), 1);
    await page.mouse.up();
    assert.deepEqual(errors, []);
    assert.equal(await page.locator('.blog-image-row img').count(), 2);
    await page.getByRole('button', { name: '与上一张并排', exact: true }).last().click();
    assert.equal(await page.locator('.blog-image-row img').count(), 3);
    const boxes = await page.locator('.blog-image-row img').evaluateAll(images => images.map(image => ({ x: image.getBoundingClientRect().x, y: image.getBoundingClientRect().y, width: image.getBoundingClientRect().width })));
    assert.ok(boxes.every(box => Math.abs(box.y - boxes[0].y) < 1), 'Three images share a row');
    assert.ok(boxes[1].x >= boxes[0].x + boxes[0].width, 'Row images do not overlap');
    const rowSource = await page.locator('#markdown-editor').inputValue();
    assert.ok(rowSource.includes('中间文字') && rowSource.includes('结尾'));
    const publicRow = await page.evaluate(source => {
      const node = document.createElement('div'); node.innerHTML = renderMarkdown(source);
      return node.querySelectorAll('.blog-image-row img').length;
    }, rowSource);
    assert.equal(publicRow, 3, 'Published article keeps all row images');
    await page.locator('#markdown-editor').fill(rowSource);
    await page.locator('.image-resize-handle').first().focus();
    await page.keyboard.press('ArrowLeft');
    assert.equal(await page.locator('.blog-image-row img').count(), 3, 'Resizing preserves row membership');
    await page.getByRole('button', { name: '独占一行', exact: true }).nth(1).click();
    assert.equal(await page.locator('.blog-image-row img').count(), 2);
    assert.equal(await page.locator('#markdown-preview img').count(), 3, 'Splitting never loses or duplicates images');
    await page.locator('#markdown-editor').fill(rowSource);
    await page.screenshot({ path: '.wrangler/image-row-preview.png', fullPage: true });
    await page.locator('#markdown-editor').fill(reordered);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#markdown-preview').evaluate(el => { el.style.width = '100%'; });
    assert.ok((await img.boundingBox()).width <= 390);
    await page.locator('#markdown-editor').fill(rowSource);
    const mobileImages = await page.locator('.blog-image-row img').evaluateAll(images => images.map(image => ({ left: image.getBoundingClientRect().left, right: image.getBoundingClientRect().right })));
    assert.equal(mobileImages.length, 3);
    assert.ok(mobileImages.every(bounds => bounds.left >= 0 && bounds.right <= 390), 'Mobile row remains within the viewport');
    assert.deepEqual(errors, []);
    console.log('PASS: left-edge regression, two/three-image rows, drag joining, splitting, resize, save/reload, published rows, mobile width and existing interactions');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
